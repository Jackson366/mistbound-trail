export function get(tile: Tile): Place {
  const p = profiles[tile.id];
  const aftermath = aftermathFor(tile);
  return {
    ...p,
    intro: aftermath ? [...aftermath] : p.intro,
    points: p.points.map(([id, label, kind, x, y, title, text, clue]) => ({
      id,
      label,
      kind,
      x,
      y,
      title: aftermath && kind === "core" ? "印记已取回" : title,
      text: aftermath && kind === "core" ? aftermath.join("") : text,
      clue,
    })),
    kind:
      tile.id === 0
        ? "tavern"
        : tile.id === 7
          ? "altar"
          : tile.id === 12
            ? "crypt"
            : tile.id === 16
              ? "tower"
              : tile.id === 9
                ? "abbey"
                : tile.id === 14
                  ? "gate"
                  : ["settlement", "lair", "dungeon"].includes(tile.feature)
                    ? (
                        {
                          settlement: "camp",
                          lair: "den",
                          dungeon: "crypt",
                        } as Partial<Record<string, SceneKind>>
                      )[tile.feature]!
                    : [5, 11, 13].includes(tile.id)
                      ? "water"
                      : tile.id === 17
                        ? "pass"
                        : tile.biome === "forest"
                          ? "woodland"
                          : "moor",
  };
}
export function key(tileId: number, pointId: string) {
  return `${tileId}:${pointId}`;
}
export function observe(s: GameState, pointId: string): ObservationResult {
  const tile = s.tiles[s.position],
    place = get(tile),
    point = place.points.find((p) => p.id === pointId);
  if (!point) return { ok: false, message: "这里没有这个调查点。" };
  if (s.status !== "playing")
    return { ok: false, message: "远征已经结束，可以在手记中回看发现。" };
  if (s.pending !== null)
    return { ok: false, message: "先处理此地待定的遭遇，再查看周围。" };
  const k = key(tile.id, point.id);
  s.discoveries ??= [];
  const fresh = !s.discoveries.includes(k);
  if (fresh) {
    s.discoveries.push(k);
    s.logs.unshift({
      time: s.time,
      locationId: tile.id,
      text: `${point.kind === "talk" ? "交谈" : "查看"}「${point.label}」：${point.clue ? "发现线索「" + point.clue + "」。" : point.title + "。"}`,
    });
    s.logs = s.logs.slice(0, 80);
  }
  return { ok: true, fresh, point, key: k };
}
export function clues(s: GameState, tileId?: number): Clue[] {
  return (s.discoveries || []).flatMap((k) => {
    const [a, b] = k.split(":");
    if (tileId !== undefined && Number(a) !== tileId) return [];
    const p = get(s.tiles[Number(a)]).points.find((p) => p.id === b);
    return p?.clue ? [{ ...p, locationId: Number(a), key: k }] : [];
  });
}
